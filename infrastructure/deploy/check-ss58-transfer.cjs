const fs = require('fs'), vm = require('vm'), assert = require('assert');
const {createRequire} = require('module');
const req = createRequire('/app/apps/web/package.json');
const ts = req('typescript'), ethers = req('ethers');
const source = fs.readFileSync('/overrides/finney-tao.ts','utf8');
const exportsObj = {};
vm.runInNewContext(ts.transpileModule(source,{compilerOptions:{target:ts.ScriptTarget.ES2020,module:ts.ModuleKind.CommonJS}}).outputText,{exports:exportsObj,require:req,TextEncoder,Uint8Array,BigInt});
const f=exportsObj;
const ss58='5DXq7SMZQXQrsLhXfLZoRE8JYbzkNdfHrEruZQN4i7LvH6tK';
const evm='0x814cfC546b8667efeACb3910C149aD3053708f8E';
const hash=req('@noble/hashes/blake2b').blake2b;
const expectedKey=ethers.hexlify(hash(ethers.concat?ethers.getBytes(ethers.concat([ethers.toUtf8Bytes('evm:'),evm])):[],{dkLen:32}));
assert.equal(f.decodeFinneyAddress(ss58),expectedKey);
assert.equal(f.encodeFinneyAddress(expectedKey),ss58);
assert.equal(f.decodeFinneyAddress('finney:'+ss58),expectedKey);
assert.throws(()=>f.decodeFinneyAddress(ss58.slice(0,-1)+'J'),/checksum/);
assert.throws(()=>f.decodeFinneyAddress('tao:'+ss58));
assert.throws(()=>f.decodeFinneyAddress('5'+ '0'.repeat(47)));
assert.throws(()=>f.decodeFinneyAddress(f.encodeFinneyAddress('0x'+'00'.repeat(32))),/zero account/);
const tx=f.createSs58Transfer(ss58,'0.002',ethers.ZeroAddress,'964');
assert.equal(tx.to,'0x0000000000000000000000000000000000000800');
assert.equal(tx.operation,0);assert.equal(tx.value,'2000000000000000');
assert.equal(tx.data,new ethers.Interface(['function transfer(bytes32) payable']).encodeFunctionData('transfer',[expectedKey]));
assert.equal(f.decodeSs58Transfer('964',tx.to,tx.data,tx.value,0).recipient,ss58);
for(const amount of ['0','-1','0.0000000001','1e-3','abc']) assert.throws(()=>f.createSs58Transfer(ss58,amount,ethers.ZeroAddress,'964'));
assert.equal(f.nativeTaoValue('0.000000001'),1000000000n);
assert.equal(f.nativeTaoValue('0.002000000000000000'),2000000000000000n);
assert.throws(()=>f.createSs58Transfer(ss58,'1',evm,'964'),/native TAO/);
assert.throws(()=>f.createSs58Transfer(ss58,'1',ethers.ZeroAddress,'1'),/Finney/);
assert.match(f.validateSs58Recipient(ss58,ethers.ZeroAddress,true),/approval/);
for(const args of [['1',tx.to,tx.data,tx.value,0],['964',evm,tx.data,tx.value,0],['964',tx.to,tx.data,tx.value,1],['964',tx.to,tx.data+'00',tx.value,0],['964',tx.to,tx.data,'1',0]]) assert.equal(f.decodeSs58Transfer(...args),undefined);
